CREATE TABLE "public"."ClothingInvestor" (
    "id" TEXT NOT NULL,
    "createdAt" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMPTZ(6) NOT NULL,
    "name" VARCHAR(255) NOT NULL,
    "email" VARCHAR(255) NOT NULL DEFAULT '',
    "phone" VARCHAR(100) NOT NULL DEFAULT '',
    "address" VARCHAR(1000) NOT NULL DEFAULT '',
    "bankName" VARCHAR(255) NOT NULL DEFAULT '',
    "accountName" VARCHAR(255) NOT NULL DEFAULT '',
    "accountNumber" VARCHAR(100) NOT NULL DEFAULT '',
    "notes" VARCHAR(2000) NOT NULL DEFAULT '',
    CONSTRAINT "ClothingInvestor_pkey" PRIMARY KEY ("id")
);

CREATE TABLE "public"."ClothingInvestmentAgreement" (
    "id" TEXT NOT NULL,
    "createdAt" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMPTZ(6) NOT NULL,
    "investorId" TEXT NOT NULL,
    "reference" VARCHAR(100) NOT NULL,
    "effectiveDate" VARCHAR(10) NOT NULL,
    "principal" DECIMAL(14,2) NOT NULL,
    "monthlyRateBps" INTEGER NOT NULL DEFAULT 500,
    "notes" VARCHAR(2000) NOT NULL DEFAULT '',
    CONSTRAINT "ClothingInvestmentAgreement_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "ClothingInvestmentAgreement_principal_check" CHECK ("principal" > 0),
    CONSTRAINT "ClothingInvestmentAgreement_rate_check" CHECK ("monthlyRateBps" BETWEEN 1 AND 10000),
    CONSTRAINT "ClothingInvestmentAgreement_investorId_fkey" FOREIGN KEY ("investorId") REFERENCES "public"."ClothingInvestor"("id") ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE "public"."ClothingInvestorBankClosure" (
    "id" TEXT NOT NULL,
    "date" VARCHAR(10) NOT NULL,
    "name" VARCHAR(255) NOT NULL,
    "createdAt" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMPTZ(6) NOT NULL,
    "deletedAt" TIMESTAMPTZ(6),
    CONSTRAINT "ClothingInvestorBankClosure_pkey" PRIMARY KEY ("id")
);

CREATE INDEX "ClothingInvestor_name_idx" ON "public"."ClothingInvestor"("name");
CREATE UNIQUE INDEX "ClothingInvestmentAgreement_reference_key" ON "public"."ClothingInvestmentAgreement"("reference");
CREATE INDEX "ClothingInvestmentAgreement_investorId_idx" ON "public"."ClothingInvestmentAgreement"("investorId");
CREATE INDEX "ClothingInvestmentAgreement_effectiveDate_idx" ON "public"."ClothingInvestmentAgreement"("effectiveDate");
